"""Wire contracts: activity inputs/outputs, workflow input, signals, queries.

Kept separate from the artifacts they carry because these are *protocol*. Once a
workflow is running in production, changing one of these shapes is a versioning
event; changing a field on `MigrationSpec` is not. Every activity therefore
takes exactly one argument and returns exactly one value, which is what makes a
field addition backwards compatible.
"""

