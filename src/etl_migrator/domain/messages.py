#: One week. Long enough that a HIGH-risk migration can wait for a human who is
#: on holiday, which is exactly the scenario durable execution exists for.
DEFAULT_APPROVAL_TIMEOUT_SECONDS = 7 * 24 * 60 * 60


# --------------------------------------------------------------------------
# Telemetry
# --------------------------------------------------------------------------
class ToolResult(StrictModel):
    name: str
    is_error: bool
    preview: str


class AgentTelemetry(StrictModel):
    """Evidence that an agent did what it claims. Feeds Prometheus."""

    agent: str
    tools_used: list[str] = Field(default_factory=list)
    llm_turns: int = 0
    duration_seconds: float = 0.0
    gate_iterations: int | None = Field(
        default=None, description="Code-generation only: gate submissions the agent needed."
    )
    tool_results: list[ToolResult] = Field(default_factory=list)


# --------------------------------------------------------------------------
# Workflow input
# --------------------------------------------------------------------------
class MigrationWorkflowInput(StrictModel):
    """Input to `ETLMigrationWorkflow`.

    `migration_id` is generated by the caller, not the workflow, and is used as
    the Temporal workflow id. That gives deduplication for free: submitting the
    same migration id twice attaches to the running execution instead of
    starting a second one.
    """

    migration_id: str
    source_path: str
    input_dir: str
    output_filename: str
    scenario: str = Field(
        default="customer_pipeline",
        description="Fixture scenario when the scripted provider is configured.",
    )
    approval_timeout_seconds: int = Field(
        default=DEFAULT_APPROVAL_TIMEOUT_SECONDS, ge=1
    )
    run_generated_tests: bool = Field(
        default=True, description="Generate and execute a pytest suite during validation."
    )
    validation_timeout_seconds: int = Field(
        default=2 * 60 * 60,
        ge=60,
        description="Ceiling for the whole validation child workflow, which executes "
        "both pipelines and may run Spark for a long time.",
    )
    repair_enabled: bool = Field(
        default=True, description="Attempt autonomous repair when validation fails."
    )
    max_repair_attempts: int = Field(
        default=3,
        ge=1,
        le=10,
        description="Distinct strategies to try. Small on purpose: an agent that "
        "cannot fix it in three genuinely different ways is not converging.",
    )
    repair_timeout_seconds: int = Field(default=6 * 60 * 60, ge=60)
    optimize_enabled: bool = Field(
        default=True, description="Benchmark and attempt optimisation once correct."
    )
    max_optimization_attempts: int = Field(default=2, ge=1, le=5)
    benchmark_runs: int = Field(default=DEFAULT_RUNS, ge=2, le=20)
    min_speedup: float = Field(
        default=DEFAULT_MIN_SPEEDUP,
        gt=1.0,
        description="Below this the change is not worth the review burden even if real.",
    )
    optimization_timeout_seconds: int = Field(default=4 * 60 * 60, ge=60)
    execution_task_queue: str = Field(
        default="",
        description="Task queue for the activities that execute untrusted generated "
        "code. Empty means the workflow's own queue, which is correct for a single "
        "worker; set it and those activities are dispatched to a worker deployed "
        "with no internet egress (see k8s/).",
    )
    deliver_enabled: bool = Field(
        default=True,
        description="Open a pull request when the migration finishes. Runs on "
        "failure too — see `decide_delivery` for what each outcome gets.",
    )
    delivery_branch_prefix: str = "etl-migration"
    delivery_directory: str = "migrations"
    delivery_timeout_seconds: int = Field(default=30 * 60, ge=60)


