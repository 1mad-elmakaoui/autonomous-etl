class StaticAnalysisOutput(StrictModel):
    """The independent gate verdict.

    Returned as *data* rather than raised as an error on purpose. A failing gate
    is a legitimate outcome the workflow must reason about, since it routes to the
    repair loop, and an exception would hand that decision to a retry
    policy instead.
    """

    result: CodeGenResult

    @property
    def passed(self) -> bool:
        return self.result.static_analysis.passed

    @property
    def report(self) -> StaticAnalysisReport:
        return self.result.static_analysis


